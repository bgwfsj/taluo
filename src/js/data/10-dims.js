function todayReadingFor(card, orientation) {
  const o = orientation === 'reversed' ? 'r' : 'u';
  if (card.arcana === 'major') {
    const today = card[orientation].today || {};
    const out = {};
    for (const dim of DIMENSIONS) out[dim.key] = today[dim.key] || '';
    return out;
  }
  const suit = SUIT_DIM_TODAY[card.suit];
  const rank = RANK_TODAY[card.rank] || RANK_TODAY.ace;
  const out = {};
  for (const dim of DIMENSIONS) out[dim.key] = suit[dim.key][o] + ' ' + rank[o];
  return out;
}
