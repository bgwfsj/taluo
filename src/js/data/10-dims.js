const LUCKY_DIRECTIONS = ['东方', '南方', '西方', '北方', '东南', '西南'];
const LUCKY_TIMES = ['清晨', '午后', '黄昏', '夜晚'];

function luckyFor(card, orientation) {
  const h = stableHash(card.id + (orientation === 'reversed' ? 'r' : 'u'));
  return {
    color: LUCKY_COLORS[h % LUCKY_COLORS.length],
    number: (h % 9) + 1,
    direction: LUCKY_DIRECTIONS[(h >>> 3) % LUCKY_DIRECTIONS.length],
    time: LUCKY_TIMES[(h >>> 5) % LUCKY_TIMES.length]
  };
}

// 返回 { theme, do, dont, lucky, bless }
function todayExtraFor(card, orientation) {
  const o = orientation === 'reversed' ? 'reversed' : 'upright';
  const lucky = luckyFor(card, o);
  if (card.arcana === 'major') {
    const e = (MAJOR_TODAY_EXTRA[card.id] || {})[o];
    const d = (MAJOR_TODAY_DEEP[card.id] || {})[o];
    const fallback = card[o].summary;
    return {
      theme: e ? e.theme : fallback,
      overview: d ? d.overview : fallback,
      do: e ? e.do.slice(0, 3) : [],
      dont: e ? e.dont.slice(0, 3) : [],
      lucky: lucky,
      bless: e ? e.bless : fallback
    };
  }
  const suit = SUIT_TODAY_EXTRA[card.suit];
  const rank = RANK_TODAY[card.rank] || RANK_TODAY.ace;
  const o1 = o === 'reversed' ? 'r' : 'u';
  const h = stableHash(card.id + o1);
  return {
    theme: suit['theme' + (o === 'reversed' ? 'R' : 'U')],
    overview: SUIT_OVERVIEW[card.suit][o1] + ' ' + rank[o1],
    do: pickStable(suit.do, 3, h),
    dont: pickStable(suit.dont, 3, h + 7),
    lucky: lucky,
    bless: suit.bless[h % suit.bless.length]
  };
}




